QString cp1250ToUnicode(const QByteArray &encoded)
{
    QString result;
    result.reserve(encoded.size());

    for (auto const byte : encoded)
    {
        auto const value = static_cast<unsigned char>(byte);
        result.append(value < 0x80 ? QChar{value} : QChar{Cp1250[value - 0x80]});
    }

    return result;
}
